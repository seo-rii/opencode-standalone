test("snapshots match Git tree IDs, preserve the source index, and restore text, binary, symlinks and modes", { timeout: 30_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  const worktree = path.join(root, "work")
  await fs.mkdir(path.join(worktree, "a"), { recursive: true })
  await fs.writeFile(path.join(worktree, ".gitignore"), "ignored.txt\n")
  await fs.writeFile(path.join(worktree, "hello.txt"), "one\ntwo\n")
  await fs.writeFile(path.join(worktree, "a", "한글.txt"), "nested\n")
  await fs.writeFile(path.join(worktree, "executable.sh"), "#!/bin/sh\nprintf hello\n", { mode: 0o755 })
  await fs.writeFile(path.join(worktree, "binary.dat"), Buffer.from([0, 1, 2, 3]))
  await fs.writeFile(path.join(worktree, "ignored.txt"), "ignored\n")
  await fs.symlink("hello.txt", path.join(worktree, "link"))
  native(worktree, ["init", "--initial-branch=main"])
  native(worktree, ["add", "-A"])
  native(worktree, ["-c", "user.name=Standalone Test", "-c", "user.email=test@example.invalid", "commit", "-m", "fixture"])
  native(worktree, ["update-index", "--index-version=4"])
  const source = await discover(path.join(worktree, "a"))
  assert.ok(source)
  const originalIndex = await fs.readFile(path.join(source.gitDirectory, "index"))
  assert.equal(originalIndex.readUInt32BE(4), 4)
  assert.equal(readIndex(originalIndex).size, 6)
  assert.equal(await branch(source), "main")
  assert.equal(await head(source), native(worktree, ["rev-parse", "HEAD"]).trim())
  assert.deepEqual(await rootCommits(source), [await head(source)])
  assert.deepEqual(await ignored({ repository: source, paths: ["ignored.txt", "hello.txt"] }), new Set(["ignored.txt"]))

  const snapshot = await create({ worktree, gitDirectory: path.join(root, "snapshot"), seed: source })
  const before = await capture({ repository: snapshot, scopes: ["."], ignores: source })
  assert.equal(before, native(worktree, ["rev-parse", "HEAD^{tree}"]).trim())
  assert.equal(await write(snapshot), before)

  // Seed blobs must still be readable after Git packs the source object store.
  native(worktree, ["repack", "-ad"])
  await fs.writeFile(path.join(worktree, "hello.txt"), "one\nchanged\nthree\n")
  await fs.rm(path.join(worktree, "a", "한글.txt"))
  await fs.writeFile(path.join(worktree, "literal[1].txt"), "new file\n")
  await fs.writeFile(path.join(worktree, "binary.dat"), Buffer.from([0, 9, 8]))
  await fs.rm(path.join(worktree, "link"))
  await fs.symlink("literal[1].txt", path.join(worktree, "link"))
  await fs.chmod(path.join(worktree, "executable.sh"), 0o644)
  const after = await capture({ repository: snapshot, scopes: ["."], ignores: source })
  const oracleIndex = path.join(root, "oracle-index")
  native(worktree, ["add", "-A"], oracleIndex)
  assert.equal(after, native(worktree, ["write-tree"], oracleIndex).trim())
  assert.equal(native(worktree, ["--git-dir", snapshot.gitDirectory, "write-tree"]).trim(), after)
  assert.deepEqual(await fs.readFile(path.join(source.gitDirectory, "index")), originalIndex)
  const changed = await files({ repository: snapshot, from: before, to: after })
  assert.deepEqual(changed, ["a/한글.txt", "binary.dat", "executable.sh", "hello.txt", "link", "literal[1].txt"])
  const changes = await diff({ repository: snapshot, from: before, to: after })
  assert.equal(changes.find((item) => item.file === "binary.dat")?.patch, "")
  assert.equal(changes.find((item) => item.file === "hello.txt")?.additions, 2)
  assert.equal(changes.find((item) => item.file === "hello.txt")?.deletions, 1)
  assert.match(changes.find((item) => item.file === "executable.sh")!.patch, /old mode 100755\nnew mode 100644/)
  assert.match(changes.find((item) => item.file === "literal[1].txt")!.patch, /^diff --git a\/literal\[1\].txt b\/literal\[1\].txt/)

  await restore({ repository: snapshot, files: new Map(changed.map((file) => [file, before])) })
  assert.equal(await fs.readFile(path.join(worktree, "hello.txt"), "utf8"), "one\ntwo\n")
  assert.equal(await fs.readlink(path.join(worktree, "link")), "hello.txt")
  assert.equal((await fs.stat(path.join(worktree, "executable.sh"))).mode & 0o777, 0o755)
  assert.equal(await capture({ repository: snapshot, scopes: ["."], ignores: source }), before)
  assert.deepEqual(await fs.readFile(path.join(source.gitDirectory, "index")), originalIndex)
})

test("scoped captures keep other paths and skip only oversized untracked files", { timeout: 15_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-scopes-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  const worktree = path.join(root, "work")
  await fs.mkdir(worktree)
  await fs.writeFile(path.join(worktree, "one"), "original\n")
  await fs.writeFile(path.join(worktree, "two"), "original\n")
  const repository = await create({ worktree, gitDirectory: path.join(root, "snapshot") })
  const first = await capture({ repository, scopes: ["."] })
  await fs.writeFile(path.join(worktree, "one"), "changed beyond limit\n")
  await fs.writeFile(path.join(worktree, "two"), "changed\n")
  await fs.writeFile(path.join(worktree, "large"), "oversized untracked file\n")
  const partial = await capture({ repository, scopes: ["one", "large"], maximumUntrackedFileBytes: 10 })
  assert.deepEqual(await files({ repository, from: first, to: partial }), ["one"])
  const full = await capture({ repository, scopes: ["."], maximumUntrackedFileBytes: 10 })
  assert.deepEqual(await files({ repository, from: first, to: full }), ["one", "two"])
  await assert.rejects(() => restore({ repository, files: new Map([["../outside", first]]) }), /Invalid repository-relative path/)
})

test("restore replaces a symlink parent without following it outside the worktree", { timeout: 15_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-restore-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  const worktree = path.join(root, "work")
  const outside = path.join(root, "outside")
  await fs.mkdir(path.join(worktree, "dir"), { recursive: true })
  await fs.mkdir(outside)
  await fs.writeFile(path.join(worktree, "dir", "file"), "snapshot")
  await fs.writeFile(path.join(outside, "file"), "outside")
  const repository = await create({ worktree, gitDirectory: path.join(root, "snapshot") })
  const tree = await capture({ repository, scopes: ["."] })
  await fs.rm(path.join(worktree, "dir"), { recursive: true })
  await fs.symlink(outside, path.join(worktree, "dir"))
  await restore({ repository, files: new Map([["dir/file", tree]]) })
  assert.equal(await fs.readFile(path.join(worktree, "dir", "file"), "utf8"), "snapshot")
  assert.equal(await fs.readFile(path.join(outside, "file"), "utf8"), "outside")
})

test("linked worktree discovery uses its own HEAD and the common objects", { timeout: 15_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-linked-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  const worktree = path.join(root, "work")
  await fs.mkdir(worktree)
  native(worktree, ["init", "--initial-branch=main"])
  native(worktree, ["-c", "user.name=Standalone Test", "-c", "user.email=test@example.invalid", "commit", "--allow-empty", "-m", "fixture"])
  const linked = path.join(root, "linked")
  native(worktree, ["worktree", "add", "--detach", linked, "HEAD"])
  const repository = await discover(linked)
  assert.ok(repository)
  assert.equal(repository.commonDirectory, path.join(worktree, ".git"))
  assert.equal(await branch(repository), undefined)
  assert.deepEqual(await rootCommits(repository), [await head(repository)])
  assert.deepEqual(await listWorktrees(repository), [{ directory: worktree, kind: "main" }, { directory: linked, kind: "linked" }])
  await removeWorktree({ repository, directory: linked, force: false })
  assert.equal(native(worktree, ["worktree", "list", "--porcelain"]).includes(linked), false)
})

test("linked worktree creation interoperates with Git and removal protects modified, staged and untracked files", { timeout: 15_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-worktree-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  const worktree = path.join(root, "work")
  await fs.mkdir(worktree)
  await fs.writeFile(path.join(worktree, "file"), "committed\n")
  await fs.writeFile(path.join(worktree, ".gitignore"), "ignored\n")
  await fs.symlink("file", path.join(worktree, "link"))
  native(worktree, ["init", "--initial-branch=main"])
  native(worktree, ["add", "-A"])
  native(worktree, ["-c", "user.name=Standalone Test", "-c", "user.email=test@example.invalid", "commit", "-m", "fixture"])
  const repository = (await discover(worktree))!
  const sourceIndex = await fs.readFile(path.join(repository.gitDirectory, "index"))
  const linked = await createWorktree({ repository, directory: path.join(root, "linked"), ref: "main" })
  assert.equal(await branch(linked), undefined)
  assert.equal(native(linked.worktree, ["rev-parse", "HEAD"]).trim(), await head(repository))
  assert.equal(native(linked.worktree, ["status", "--porcelain"]), "")
  assert.equal(await fs.readlink(path.join(linked.worktree, "link")), "file")
  assert.match(native(worktree, ["worktree", "list", "--porcelain"]), /linked\nHEAD [a-f0-9]{40}\ndetached/)
  await assert.rejects(() => removeWorktree({ repository, directory: worktree, force: true }), /main worktree/)
  await fs.writeFile(path.join(linked.worktree, "file"), "changed\n")
  await assert.rejects(() => removeWorktree({ repository, directory: linked.worktree, force: false }), { forceRequired: true })
  native(linked.worktree, ["add", "file"])
  await assert.rejects(() => removeWorktree({ repository, directory: linked.worktree, force: false }), { forceRequired: true })
  await removeWorktree({ repository, directory: linked.worktree, force: true })
  assert.equal(native(worktree, ["worktree", "list", "--porcelain"]).includes(linked.worktree), false)
  assert.deepEqual(await fs.readFile(path.join(repository.gitDirectory, "index")), sourceIndex)

  const again = await createWorktree({ repository, directory: linked.worktree })
  await fs.writeFile(path.join(again.worktree, "untracked"), "preserve")
  await assert.rejects(() => removeWorktree({ repository, directory: again.worktree, force: false }), { forceRequired: true })
  await fs.rm(path.join(again.worktree, "untracked"))
  await fs.writeFile(path.join(again.gitDirectory, "locked"), "test lock")
  await assert.rejects(() => removeWorktree({ repository, directory: again.worktree, force: true }), /locked/)
  await fs.rm(path.join(again.gitDirectory, "locked"))
  await fs.writeFile(path.join(again.worktree, "ignored"), "ignored content")
  await removeWorktree({ repository, directory: again.worktree, force: false })
  assert.deepEqual(await listWorktrees(repository), [{ directory: worktree, kind: "main" }])

  await fs.mkdir(linked.worktree)
  await fs.writeFile(path.join(linked.worktree, "existing"), "preserve")
  await assert.rejects(() => createWorktree({ repository, directory: linked.worktree }), /empty directory/)
  assert.equal(await fs.readFile(path.join(linked.worktree, "existing"), "utf8"), "preserve")
})

test("object packing preserves unreferenced snapshots, combines packs and leaves kept packs intact", { timeout: 15_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-pack-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  const worktree = path.join(root, "work")
  await fs.mkdir(worktree)
  const repository = await create({ worktree, gitDirectory: path.join(root, "snapshot") })
  const directory = path.join(repository.gitDirectory, "objects", "pack")
  const trees: string[] = []
  await fs.writeFile(path.join(worktree, "file"), "first snapshot\n")
  trees.push(await capture({ repository, scopes: ["."] }))
  await pack(repository)
  assert.deepEqual(await fs.readdir(directory), [])
  await pack(repository, { looseObjectLimit: 2 })
  const kept = (await fs.readdir(directory)).find((file) => file.endsWith(".pack"))!
  const keptBytes = await fs.readFile(path.join(directory, kept))
  await fs.writeFile(path.join(directory, kept.replace(/\.pack$/, ".keep")), "keep this pack\n")
  for (const text of ["second", "third"]) {
    await fs.writeFile(path.join(worktree, "file"), `${text} snapshot\n`)
    trees.push(await capture({ repository, scopes: ["."] }))
    await pack(repository, { looseObjectLimit: 2 })
  }
  assert.equal((await fs.readdir(directory)).filter((file) => file.endsWith(".pack")).length, 3)
  native(worktree, ["--git-dir", repository.gitDirectory, "multi-pack-index", "write"])
  await pack(repository, { packCountLimit: 2 })
  const packed = (await fs.readdir(directory)).filter((file) => file.endsWith(".pack"))
  assert.equal(packed.length, 2)
  assert.ok(packed.includes(kept))
  assert.deepEqual(await fs.readFile(path.join(directory, kept)), keptBytes)
  for (const file of packed) native(worktree, ["verify-pack", path.join(directory, file.replace(/\.pack$/, ".idx"))])
  const indexPath = path.join(directory, packed.find((file) => file !== kept)!.replace(/\.pack$/, ".idx"))
  const originalIndex = await fs.readFile(indexPath)
  const damagedIndex = Buffer.from(originalIndex)
  damagedIndex[damagedIndex.length - 1] ^= 1
  await fs.writeFile(indexPath, damagedIndex)
  await assert.rejects(() => pack(repository, { packCountLimit: 1 }), /checksum mismatch/)
  assert.deepEqual((await fs.readdir(directory)).filter((file) => file.endsWith(".pack")), packed)
  await fs.writeFile(indexPath, originalIndex)
  for (const tree of trees) assert.match(native(worktree, ["--git-dir", repository.gitDirectory, "ls-tree", tree]), /100644 blob [0-9a-f]{40}\tfile/)
  await restore({ repository, files: new Map([["file", trees[0]]]) })
  assert.equal(await fs.readFile(path.join(worktree, "file"), "utf8"), "first snapshot\n")
  assert.deepEqual(await files({ repository, from: trees[0], to: trees[2] }), ["file"])
  assert.equal((await fs.readdir(directory)).some((file) => file.startsWith("tmp-")), false)
  assert.equal((await fs.readdir(repository.gitDirectory)).includes("opencode-pack.lock"), false)
})

test("remote branch checkout resets by default but preserves conflicting local edits and branch pointers", { timeout: 15_000 }, async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "standalone-git-checkout-"))
  t.after(() => fs.rm(root, { force: true, recursive: true }))
  native(root, ["init", "--initial-branch=main"])
  await fs.writeFile(path.join(root, "file"), "first\n")
  native(root, ["add", "file"])
  native(root, ["-c", "user.name=Standalone Test", "-c", "user.email=test@example.invalid", "commit", "-m", "first"])
  const repository = (await discover(root))!
  const first = (await head(repository))!
  await fs.writeFile(path.join(root, "file"), "remote\n")
  native(root, ["-c", "user.name=Standalone Test", "-c", "user.email=test@example.invalid", "commit", "-am", "remote"])
  const remote = (await head(repository))!
  native(root, ["update-ref", "refs/remotes/origin/main", remote])
  native(root, ["reset", "--hard", first])
  await checkoutRemoteBranch(repository, { branch: "main", reset: false })
  assert.equal(await head(repository), first)
  await fs.writeFile(path.join(root, "file"), "local edits\n")
  await assert.rejects(() => checkoutRemoteBranch(repository, { branch: "main" }), /changes|overwritten|conflict/i)
  assert.equal(await head(repository), first)
  assert.equal(await fs.readFile(path.join(root, "file"), "utf8"), "local edits\n")
  await fs.writeFile(path.join(root, "file"), "first\n")
  await checkoutRemoteBranch(repository, { branch: "main" })
  assert.equal(await head(repository), remote)
  assert.equal(await branch(repository), "main")
  assert.equal(native(root, ["status", "--porcelain"]), "")
  await resetHard(repository, first)
  assert.equal(await head(repository), first)
  assert.equal(await fs.readFile(path.join(root, "file"), "utf8"), "first\n")
})

function native(directory: string, args: string[], index?: string) {
  return execFileSync("git", ["-c", "core.autocrlf=false", "-c", "core.filemode=true", "-C", directory, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null", ...(index ? { GIT_INDEX_FILE: index } : {}) },
  })
}
