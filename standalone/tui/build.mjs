import { createHash } from "node:crypto"
import { access, mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { spawnSync } from "node:child_process"
import { fileURLToPath } from "node:url"
import { bundleDemo } from "./bundle-demo.mjs"

const directory = dirname(fileURLToPath(import.meta.url))
const cache = join(directory, ".cache")
const upstream = join(cache, "upstream")
const manifest = JSON.parse(await readFile(join(directory, "sources.json"), "utf8"))
await mkdir(upstream, { recursive: true })
for (const source of manifest.sources) {
  await download(source.url, join(upstream, source.path), source.sha256)
}
await mkdir(join(upstream, "zig-deps"), { recursive: true })
run("tar", ["-xzf", join(upstream, "zig-deps.tar.gz"), "-C", join(upstream, "zig-deps"), "uucode-opentui"])
const notices = [
  ["OpenTUI 0.6.6", "LICENSE"],
  ["uucode 0.2.0 (OpenTUI vendored source)", "zig-deps/uucode-opentui/LICENSE.md"],
  ["Unicode Character Database", "UUCODE-UNICODE-LICENSE"],
  ["UTF-8 decoder notice retained from uucode", "UUCODE-UTF8-LICENSE"],
]
const licenses = (await Promise.all(notices.map(async ([name, path]) => `${name}\n${"=".repeat(name.length)}\n\n${await readFile(join(upstream, path), "utf8")}`))).join("\n\n")
await writeFile(join(directory, "LICENSES.txt"), licenses)

const zig = process.env.OPENCODE_ZIG ?? join(cache, "zig", "zig")
if (!(await access(zig).then(() => true, () => false))) {
  if (process.env.OPENCODE_ZIG || process.platform !== "linux" || process.arch !== "x64") {
    throw new Error(`Set OPENCODE_ZIG to a Zig ${manifest.zig.version} executable for this build host.`)
  }
  const archive = join(cache, "zig.tar.xz")
  await download(manifest.zig.url, archive, manifest.zig.sha256)
  await mkdir(join(cache, "zig"), { recursive: true })
  run("tar", ["-xJf", archive, "-C", join(cache, "zig"), "--strip-components=1"])
}
const version = spawnSync(zig, ["version"], { encoding: "utf8" })
if (version.status !== 0 || version.stdout.trim() !== manifest.zig.version) {
  throw new Error(`Expected Zig ${manifest.zig.version}; got ${version.stdout.trim() || version.error?.message}`)
}
run(zig, ["build", "-j2", "--prefix", join(cache, "build"), "--cache-dir", join(cache, "zig-build"), "--global-cache-dir", join(cache, "zig-global")])
const wasm = await readFile(join(cache, "build", "bin", "opentui-unicode.wasm"))
const module = new WebAssembly.Module(wasm)
if (WebAssembly.Module.imports(module).length !== 0) throw new Error("The Unicode WASM proof must not import host functions.")
const embedded = `/*!\n${licenses.replaceAll("*/", "* /")}\n*/\n// Generated by standalone/tui/build.mjs; do not edit.\n// OpenTUI ${manifest.opentuiVersion} ${manifest.opentuiCommit}\n// WASM SHA-256: ${createHash("sha256").update(wasm).digest("hex")}\nexport const wasmBase64 = ${JSON.stringify(wasm.toString("base64"))}\n`
await writeFile(join(directory, "unicode-wasm.mjs"), embedded)

// The proof artifact can be copied by itself to a machine with only Node.
// There is no runtime loader, extraction, FFI flag, or asset-directory fallback.
await bundleDemo(join(cache, "opentui-unicode-demo.mjs"))
console.log(JSON.stringify({ wasmBytes: wasm.length, imports: [], demo: join(cache, "opentui-unicode-demo.mjs") }))

async function download(url, destination, sha256) {
  const existing = await readFile(destination).catch((error) => {
    if (error.code !== "ENOENT") throw error
  })
  const bytes = existing ?? Buffer.from(await fetch(url).then((response) => {
    if (!response.ok) throw new Error(`Download failed (${response.status}): ${url}`)
    return response.arrayBuffer()
  }))
  if (createHash("sha256").update(bytes).digest("hex") !== sha256) throw new Error(`Source checksum mismatch: ${destination}`)
  if (!existing) await writeFile(destination, bytes)
}

function run(command, args) {
  const result = spawnSync(command, args, { cwd: directory, stdio: "inherit" })
  if (result.status !== 0) throw result.error ?? new Error(`${command} failed (${result.status ?? result.signal})`)
}

